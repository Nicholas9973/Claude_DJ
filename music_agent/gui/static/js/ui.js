/** An inline SVG icon by name. */
export function icon(name, cls = "icon") {
  const span = document.createElement("span");
  span.innerHTML = `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] || ""}</svg>`;
  return span.firstElementChild;
}

/** Show a short message in the corner. kind: "info" | "error". */
export function toast(message, kind = "info") {
  const el = h("div", { class: `toast ${kind}` }, message);
  document.getElementById("toasts").append(el);
  setTimeout(() => el.remove(), kind === "error" ? 6000 : 3500);
}

/** Run an async action, showing any error as a toast. Returns the result or undefined. */
export async function attempt(action) {
  try {
    return await action();
  } catch (err) {
    toast(err.message, "error");
    return undefined;
  }
}

/** 234 -> "3:54". */
export function clock(seconds) {
  if (seconds === null || seconds === undefined || Number.isNaN(seconds)) return "-:--";
  const s = Math.max(0, Math.round(seconds));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

/** "2026-10-04T18:30:00" -> "5 min ago" / "yesterday" / "3 Oct". */
export function ago(iso) {
  if (!iso) return "";
  const then = new Date(iso);
  const s = (Date.now() - then.getTime()) / 1000;
  if (s < 60) return "just now";
  if (s < 3600) return `${Math.floor(s / 60)} min ago`;
  if (s < 86400) return `${Math.floor(s / 3600)} h ago`;
  if (s < 172800) return "yesterday";
  return then.toLocaleDateString(undefined, { day: "numeric", month: "short" });
}

function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

/** Minimal, safe Markdown for agent replies: paragraphs, bullet lists, **bold**, *italic*, `code`. */
export function markdown(text) {
  const inline = (s) => escapeHtml(s)
    .replace(/\*\*(.+?)\*\*/g, "<b>$1</b>")
    .replace(/(^|[^*])\*([^*]+)\*/g, "$1<i>$2</i>")
    .replace(/`([^`]+)`/g, "<code>$1</code>");
  const out = [];
  for (const block of text.trim().split(/\n{2,}/)) {
    const lines = block.split("\n");
    if (lines.every((l) => /^\s*([-*]|\d+\.)\s+/.test(l))) {
      out.push(`<ul>${lines.map((l) => `<li>${inline(l.replace(/^\s*([-*]|\d+\.)\s+/, ""))}</li>`).join("")}</ul>`);
    } else {
      out.push(`<p>${lines.map(inline).join("<br>")}</p>`);
    }
  }
  return out.join("");
}

/** Call `fn` now and then every `ms` while the tab is visible. Returns a stop function. */
export function every(ms, fn) {
  let timer = null;
  const tick = () => { if (!document.hidden) fn(); };
  tick();
  timer = setInterval(tick, ms);
  const onVisible = () => { if (!document.hidden) fn(); };
  document.addEventListener("visibilitychange", onVisible);
  return () => { clearInterval(timer); document.removeEventListener("visibilitychange", onVisible); };
}
